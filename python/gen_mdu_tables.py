#!/usr/bin/env python3
"""Generate python/mdu_tables.py from Microsoft's reference Verilog (mdu_minirans.v).

Source: https://github.com/microsoft/silicon-rans (MIT License, Copyright (c) Microsoft
Corporation). The five lookup tables of the MDU rANS decoder (base_table, freq_table,
rf_table, rs_table, rn_table, each [9 alphabet widths][16 models][10 segments]) are read
programmatically from the .v file so no value is transcribed by hand.

Usage:
    python3 -I python/gen_mdu_tables.py /path/to/mdu_minirans.v > python/mdu_tables.py
"""
import re
import sys

TABLES = ("base_table", "freq_table", "rf_table", "rs_table", "rn_table")


def strip_comments(src: str) -> str:
    src = re.sub(r"/\*.*?\*/", "", src, flags=re.S)
    return re.sub(r"//[^\n]*", "", src)


def parse_table(src: str, name: str):
    """Return table[9][16][10] parsed from `assign <name> = '{ ... };`."""
    m = re.search(r"assign\s+%s\s*=\s*'\{" % name, src)
    if not m:
        raise SystemExit(f"table {name} not found")
    i = m.end() - 1  # at the opening '{'
    depth = 0
    j = i
    while True:
        c = src[j]
        if c == "{":
            depth += 1
        elif c == "}":
            depth -= 1
            if depth == 0:
                break
        j += 1
    body = src[i : j + 1]
    nums = [int(x) for x in re.findall(r"\d+", body)]
    if len(nums) != 9 * 16 * 10:
        raise SystemExit(f"{name}: expected 1440 values, got {len(nums)}")
    it = iter(nums)
    return [[[next(it) for _ in range(10)] for _ in range(16)] for _ in range(9)]


def main() -> int:
    path = sys.argv[1]
    raw = open(path, encoding="utf-8").read()
    src = strip_comments(raw)
    defines = {
        k: v.strip()
        for k, v in re.findall(r"^`define\s+(\w+)\s+(.*?)\s*(?://.*)?$", raw, flags=re.M)
    }
    out = [
        '"""MDU rANS lookup tables, generated by python/gen_mdu_tables.py. Do not edit.',
        "",
        "Generated from mdu_minirans.v in https://github.com/microsoft/silicon-rans",
        "(MIT License, Copyright (c) Microsoft Corporation). Indexing is",
        "TABLE[eab][q][seg] where eab = alphabet bits - 1 (index 0 is the 1-bit alphabet),",
        "q = static model 0..15 and seg = 0..9 (seg 0 = symbol 0, seg k = symbols",
        "[2^(k-1), 2^k)).",
        '"""',
        "",
        f"VERILOG_DEFINES = {defines!r}",
        "",
    ]
    for name in TABLES:
        t = parse_table(src, name)
        out.append(f"{name.upper()} = (")
        for eab in range(9):
            out.append(f"    (  # alphabet size = {eab + 1} bits")
            for q in range(16):
                out.append(f"        {tuple(t[eab][q])!r},")
            out.append("    ),")
        out.append(")")
        out.append("")
    sys.stdout.write("\n".join(out))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
