#!/usr/bin/env python3
"""Generate the MDU rANS model tables from Microsoft's reference Verilog.

usage: python3 -I tools/gen_tables.py path/to/silicon-rans/mdu_minirans.v

Source: https://github.com/microsoft/silicon-rans (mdu_minirans.v, MIT License,
Copyright (c) Microsoft Corporation; see THIRD_PARTY_NOTICES.md).

Writes:
  src/tables.rs            Rust constants
  python/bcpack_tables.py     the same tables for the Python reference decoder

Both files carry a SHA-256 over a canonical serialisation of the five tables,
and the test suites recompute it, so a hand edit is caught. The tables are
never typed by hand.
"""
import hashlib
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
NAMES = ("base_table", "freq_table", "rf_table", "rs_table", "rn_table")


def parse(path):
    src = open(path).read()
    out = {}
    for name in NAMES:
        m = re.search(r"assign\s+%s\s*=\s*'\{(.*?)\}\s*;\s*//\s*end %s" % (name, name), src, re.S)
        body = re.sub(r"//[^\n]*", "", m.group(1))
        nums = [int(x) for x in re.findall(r"\d+", body)]
        assert len(nums) == 9 * 16 * 10, (name, len(nums))
        out[name] = nums
    return out


def checksum(t):
    """SHA-256 of the five tables as decimal text: one line per table, values
    comma separated, in the order base, freq, rf, rs, rn; flat index = (eab*16+q)*10+seg."""
    text = "".join(",".join(map(str, t[n])) + "\n" for n in NAMES)
    return hashlib.sha256(text.encode()).hexdigest()


HEADER = """Exact rANS model tables of the Xbox Series MDU decoder.

Generated by tools/gen_tables.py from mdu_minirans.v in
https://github.com/microsoft/silicon-rans (commit 2f6827d), MIT License,
Copyright (c) Microsoft Corporation. See THIRD_PARTY_NOTICES.md. Do not edit.

Index [eab][q][seg]: eab = alphabet bits - 1 (0..8), q = model (0..15),
seg = 0 for symbol 0, k >= 1 for symbols [2^(k-1), 2^k)."""


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    vpath = sys.argv[1]
    t = parse(vpath)
    h = checksum(t)
    rs = ["// " + l if l else "//" for l in HEADER.split("\n")]
    rs.append("")
    rs.append('/// SHA-256 of the canonical table text (see `tools/gen_tables.py`).')
    rs.append('pub const TABLES_SHA256: &str = "%s";' % h)
    types = {"base_table": "u16", "freq_table": "u16", "rf_table": "u32", "rs_table": "u8", "rn_table": "u16"}
    for n in NAMES:
        ty = types[n]
        assert max(t[n]) < (1 << {"u16": 16, "u32": 32, "u8": 8}[ty]), n
        rs.append("")
        rs.append("pub static %s: [[[%s; 10]; 16]; 9] = [" % (n.upper(), ty))
        for e in range(9):
            rs.append("    [")
            for q in range(16):
                v = t[n][(e * 16 + q) * 10:(e * 16 + q) * 10 + 10]
                rs.append("        [%s]," % ", ".join(map(str, v)))
            rs.append("    ],")
        rs.append("];")
    open(os.path.join(ROOT, "src", "tables.rs"), "w").write("\n".join(rs) + "\n")
    py = ['"""' + HEADER + '\n"""', "", 'TABLES_SHA256 = "%s"' % h, ""]
    for n in NAMES:
        py.append("%s = [" % n.upper())
        for e in range(9):
            py.append("    [")
            for q in range(16):
                v = t[n][(e * 16 + q) * 10:(e * 16 + q) * 10 + 10]
                py.append("        [%s]," % ", ".join(map(str, v)))
            py.append("    ],")
        py.append("]")
        py.append("")
    open(os.path.join(ROOT, "python", "bcpack_tables.py"), "w").write("\n".join(py))
    print("tables sha256", h)


if __name__ == "__main__":
    main()
